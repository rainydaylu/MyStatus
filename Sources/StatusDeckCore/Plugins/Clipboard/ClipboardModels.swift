enum ClipKind: String, CaseIterable, Sendable {
    case text, code, link, color, image, file

    var symbol: String {
        switch self {
        case .text: "text.alignleft"
        case .code: "chevron.left.forwardslash.chevron.right"
        case .link: "link"
        case .color: "paintpalette.fill"
        case .image: "photo"
        case .file: "doc.fill"
        }
    }
}

enum ClipFilter: String, CaseIterable, Sendable {
    case all, text, link, image, file, code, color, pinned

    var title: String {
        switch self {
        case .all: DeckL("全部")
        case .text: DeckL("文本")
        case .link: DeckL("链接")
        case .image: DeckL("图片")
        case .file: DeckL("文件")
        case .code: DeckL("代码")
        case .color: DeckL("颜色")
        case .pinned: DeckL("置顶")
        }
    }

    /// The kinds this filter shows. `nil` means no restriction on kind.
    var kinds: [ClipKind]? {
        switch self {
        case .all, .pinned: nil
        case .text: [.text]
        case .code: [.code]
        case .color: [.color]
        case .link: [.link]
        case .image: [.image]
        case .file: [.file]
        }
    }
}

struct ClipboardItem: Identifiable, Equatable, Sendable {
    let id: Int64
    let kind: ClipKind
    /// The full text, or the file paths one per line.
    let text: String?
    let preview: String
    let sourceBundleID: String?
    let sourceName: String?
    let createdAt: Date
    let isPinned: Bool
    let byteCount: Int
    let thumbnail: Data?

    var displayPreview: String {
        if kind == .image {
            let parts = preview.split(separator: " ", maxSplits: 1)
            if parts.count == 2, parts[1].contains(" × ") {
                return DeckLF("图片 %@", "Image %@", String(parts[1]))
            }
            return DeckL("图片", "Image")
        }
        if kind == .file, let text {
            let paths = text.split(separator: "\n")
            if let first = paths.first, paths.count > 1 {
                let name = URL(fileURLWithPath: String(first)).lastPathComponent
                return paths.count == 2
                    ? DeckLF("%@ 等 2 个文件", "%@ and one other file", name)
                    : DeckLF("%1$@ 及其他 %2$@ 个文件", "%1$@ and %2$@ other files", name, String(paths.count - 1))
            }
        }
        return preview
    }
}

/// One pasteboard flavor of one pasteboard item, as stored and as restored.
struct ClipRepresentation: Equatable, Sendable {
    let itemIndex: Int
    let type: String
    let data: Data
}

enum PasteboardType {
    static let plainText = "public.utf8-plain-text"
    static let fileURL = "public.file-url"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let jpeg = "public.jpeg"
    static let html = "public.html"
    static let rtf = "public.rtf"

    static let images = [png, tiff, jpeg, "com.compuserve.gif", "public.heic"]
}

/// What the capture leaves alone, following the conventions at nspasteboard.org that
/// password managers and similar tools use to mark what they put on the clipboard.
enum ClipboardPrivacy {
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "de.petermaurer.AutoGeneratedPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
        "Nv Pasteboard Type",
        "net.antelle.keeweb"
    ]

    /// Apps whose clipboard use is about secrets, recorded by nobody by default.
    static let defaultBlockedApps = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.1password.safari",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.Dashlane",
        "org.keepassxc.keepassxc"
    ]

    static func shouldSkip(types: [String], sourceBundleID: String?, blockedApps: Set<String>) -> Bool {
        if types.contains(where: sensitiveTypes.contains) { return true }
        if let sourceBundleID, blockedApps.contains(sourceBundleID) { return true }
        return false
    }
}

enum ClipboardClassifier {
    static func isLink(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.count < 4096, !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased() else {
            return false
        }
        return ["http", "https", "ftp", "ssh"].contains(scheme) && url.host != nil
    }

    /// Red, green, blue and alpha in 0...1, for the color formats people copy.
    static func color(from text: String) -> (red: Double, green: Double, blue: Double, alpha: Double)? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard trimmed.count <= 40 else { return nil }
        if trimmed.hasPrefix("#") {
            return hexColor(String(trimmed.dropFirst()))
        }
        guard trimmed.hasPrefix("rgb"), let open = trimmed.firstIndex(of: "("), trimmed.hasSuffix(")") else { return nil }
        let inside = trimmed[trimmed.index(after: open)..<trimmed.index(before: trimmed.endIndex)]
        let parts = inside.split { $0 == "," || $0 == " " || $0 == "/" }.compactMap { Double($0) }
        guard parts.count == 3 || parts.count == 4, parts[0...2].allSatisfy({ (0...255).contains($0) }) else { return nil }
        return (parts[0] / 255, parts[1] / 255, parts[2] / 255, parts.count == 4 ? min(1, parts[3]) : 1)
    }

    private static func hexColor(_ hex: String) -> (red: Double, green: Double, blue: Double, alpha: Double)? {
        guard [3, 6, 8].contains(hex.count), hex.allSatisfy(\.isHexDigit) else { return nil }
        let expanded = hex.count == 3 ? hex.map { "\($0)\($0)" }.joined() : hex
        guard let value = UInt64(expanded, radix: 16) else { return nil }
        let hasAlpha = expanded.count == 8
        let shift: UInt64 = hasAlpha ? 8 : 0
        return (
            Double((value >> (16 + shift)) & 0xFF) / 255,
            Double((value >> (8 + shift)) & 0xFF) / 255,
            Double((value >> shift) & 0xFF) / 255,
            hasAlpha ? Double(value & 0xFF) / 255 : 1
        )
    }

    /// Only decides the font a text is shown in, so a wrong guess costs little.
    /// Several lines with code punctuation or a typical opening keyword.
    static func looksLikeCode(_ text: String) -> Bool {
        let lines = text.split(separator: "\n", omittingEmptySubsequences: true)
        guard lines.count >= 2, text.count < 200_000 else { return false }
        var signals = 0
        for line in lines.prefix(60) {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.hasSuffix("{") || trimmed.hasSuffix("}") || trimmed.hasSuffix(";") || trimmed.hasSuffix("):") { signals += 1 }
            if ["func ", "def ", "class ", "import ", "#include", "const ", "let ", "var ", "return ", "public ", "if (", "for ("]
                .contains(where: trimmed.hasPrefix) { signals += 1 }
        }
        return signals >= 2 && signals * 3 >= min(lines.count, 60)
    }

    /// One line for a list: whitespace collapsed, and short enough to be cheap.
    static func preview(of text: String) -> String {
        let collapsed = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return collapsed.count > 240 ? String(collapsed.prefix(240)) + "…" : collapsed
    }
}

/// What gets stored for one copy, derived from the raw flavors alone.
struct ClipboardPayload: Equatable, Sendable {
    let kind: ClipKind
    let text: String?
    let preview: String
    let hash: String
    let representations: [ClipRepresentation]
    let thumbnail: Data?
    let byteCount: Int

    /// `items` is what the pasteboard holds: per item, its flavors in priority order.
    /// `nil` means there is nothing worth keeping, or the essential flavor is over
    /// `maxBytes`. Secondary flavors that do not fit are dropped, not the whole copy.
    static func make(items: [[(type: String, data: Data)]], maxBytes: Int) -> ClipboardPayload? {
        let all = items.enumerated().flatMap { index, flavors in
            flavors.map { ClipRepresentation(itemIndex: index, type: $0.type, data: $0.data) }
        }
        func flavors(of type: String) -> [ClipRepresentation] { all.filter { $0.type == type } }

        let plainText = flavors(of: PasteboardType.plainText).first.flatMap { String(data: $0.data, encoding: .utf8) }
        let fileURLs = flavors(of: PasteboardType.fileURL)
            .compactMap { String(data: $0.data, encoding: .utf8).flatMap(URL.init(string:)) }
            .filter(\.isFileURL)
        let image = PasteboardType.images.lazy.compactMap { flavors(of: $0).first }.first

        let kind: ClipKind
        let text: String?
        let preview: String
        let essential: [ClipRepresentation]

        if !fileURLs.isEmpty {
            kind = .file
            text = fileURLs.map(\.path).joined(separator: "\n")
            preview = fileURLs.count == 1 ? fileURLs[0].lastPathComponent : "\(fileURLs[0].lastPathComponent) 等 \(fileURLs.count) 个文件"
            essential = flavors(of: PasteboardType.fileURL)
        } else if let plainText, !plainText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            text = plainText
            preview = ClipboardClassifier.preview(of: plainText)
            if ClipboardClassifier.isLink(plainText) {
                kind = .link
            } else if ClipboardClassifier.color(from: plainText) != nil {
                kind = .color
            } else {
                kind = ClipboardClassifier.looksLikeCode(plainText) ? .code : .text
            }
            essential = flavors(of: PasteboardType.plainText)
        } else if let image {
            kind = .image
            text = nil
            let size = imagePixelSize(image.data)
            preview = size.map { "图片 \($0.width) × \($0.height)" } ?? DeckL("图片")
            essential = [image]
        } else {
            return nil
        }

        var total = essential.reduce(0) { $0 + $1.data.count }
        guard total <= maxBytes else { return nil }

        // A Finder copy also carries icon images that restoring does not need.
        var kept = essential
        if kind != .file {
            for representation in all where !essential.contains(representation) {
                guard total + representation.data.count <= maxBytes else { continue }
                total += representation.data.count
                kept.append(representation)
            }
        }

        // Identity comes from the essential flavor alone, so the same text copied
        // from two apps with different styling still counts as one entry.
        var hasher = SHA256()
        for representation in essential {
            hasher.update(data: Data(representation.type.utf8))
            hasher.update(data: representation.data)
        }
        let hash = hasher.finalize().map { String(format: "%02x", $0) }.joined()

        return ClipboardPayload(
            kind: kind,
            text: text,
            preview: preview,
            hash: hash,
            representations: kept,
            thumbnail: image.flatMap { thumbnail(of: $0.data) },
            byteCount: total
        )
    }

    private static func imagePixelSize(_ data: Data) -> (width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int else {
            return nil
        }
        return (width, height)
    }

    private static func thumbnail(of data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 480,
            kCGImageSourceCreateThumbnailWithTransform: true
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        return CGImageDestinationFinalize(destination) ? output as Data : nil
    }
}

